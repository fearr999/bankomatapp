import { z } from "zod";

// Минимум 8 символов, хотя бы одна буква и одна цифра — без экзотических
// требований (спецсимволы и т.п.), чтобы не мешать реальным сотрудникам,
// но заметно поднять планку над "123456".
export const passwordSchema = z
  .string()
  .min(8, "Минимум 8 символов")
  .regex(/[a-zA-Zа-яА-Я]/, "Пароль должен содержать хотя бы одну букву")
  .regex(/[0-9]/, "Пароль должен содержать хотя бы одну цифру");
